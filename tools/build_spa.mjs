// Build các SPA (UIF) từ spa/<tên>/ sang src/FileCabinet/SuiteScripts/com.s4.vnpayroll/spa/<tên>/.
// UIF dùng ESM và JSX, SuiteScript dùng AMD: TypeScript chuyển JSX (jsx-runtime của @uif-js/core), Rollup gộp mỗi
// entry point (SpaClient.js, SpaServer.js) thành một file AMD. Module N/ và @uif-js là external, NetSuite cung cấp.
// Cách dùng: npm run build:spa
import fs from "fs/promises";
import path from "path";
import ts from "typescript";
import { rollup } from "rollup";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const SRC = path.join(ROOT, "spa");
const BUILD = path.join(ROOT, "build", "spa");
const OUT = path.join(ROOT, "src", "FileCabinet", "SuiteScripts", "com.s4.vnpayroll", "spa");
const EXTERNAL = ["@uif-js/core", "@uif-js/core/jsx-runtime", "@uif-js/component", /^N$/, /^N\//];
const HEADER = /\/\*\*[\s\S]*?@NScriptType[\s\S]*?\*\//;
const COMPILER = {
	module: ts.ModuleKind.ES2022,
	target: ts.ScriptTarget.ES2020,
	jsx: ts.JsxEmit.ReactJSX,
	jsxImportSource: "@uif-js/core",
	allowJs: true,
};

async function files(dir) {
	const out = [];
	for (const e of await fs.readdir(dir, { withFileTypes: true })) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) out.push(...(await files(p)));
		else out.push(p);
	}
	return out;
}

async function buildApp(name) {
	const srcDir = path.join(SRC, name);
	const buildDir = path.join(BUILD, name);
	const outDir = path.join(OUT, name);
	await fs.rm(buildDir, { recursive: true, force: true });
	await fs.rm(outDir, { recursive: true, force: true });

	for (const file of await files(srcDir)) {
		const rel = path.relative(srcDir, file);
		if (!/\.(js|jsx)$/.test(file)) {
			await fs.mkdir(path.dirname(path.join(outDir, rel)), { recursive: true });
			await fs.copyFile(file, path.join(outDir, rel));
			continue;
		}
		const source = await fs.readFile(file, "utf8");
		const { outputText } = ts.transpileModule(source, { compilerOptions: COMPILER, fileName: file.replace(/\.js$/, ".jsx") });
		const target = path.join(buildDir, rel.replace(/\.jsx$/, ".js"));
		await fs.mkdir(path.dirname(target), { recursive: true });
		await fs.writeFile(target, outputText);
	}

	for (const entry of ["SpaClient.js", "SpaServer.js"]) {
		const input = path.join(buildDir, entry);
		const original = await fs.readFile(path.join(srcDir, entry), "utf8");
		const header = (original.match(HEADER) || [""])[0];
		const bundle = await rollup({
			input,
			external: EXTERNAL,
			plugins: [{ name: "strip-header", transform: (code) => code.replace(HEADER, "") }],
		});
		const { output } = await bundle.generate({ format: "amd" });
		await fs.mkdir(outDir, { recursive: true });
		const banner = "// Generated by tools/build_spa.mjs from spa/" + name + "/" + entry + ". Do not edit.\n";
		await fs.writeFile(path.join(outDir, entry), (header ? header + "\n" : "") + banner + output[0].code);
		await bundle.close();
	}
	console.log(`built spa/${name}`);
}

for (const e of await fs.readdir(SRC, { withFileTypes: true })) {
	if (e.isDirectory()) await buildApp(e.name);
}
